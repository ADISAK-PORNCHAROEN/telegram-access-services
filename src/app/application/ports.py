"""Small interfaces implemented by Telegram/filesystem adapters and test fakes."""

from collections.abc import AsyncIterable, Awaitable, Callable
from contextlib import AbstractAsyncContextManager, AbstractContextManager
from pathlib import Path
from typing import Protocol

from app.application.performance import JobTrace
from app.domain.models import (
    CopyJobInput, CopyJobSnapshot, DeliveryIntent, DeliveryOutcome, DeliveryResult,
    DownloadedMedia, JobAdmission, JobCancellationDecision, JobState, MediaItem,
    MediaKind, ParsedLink,
)
from app.domain.owner_setup import OwnerAuthResult

Progress = Callable[[int, int], None]


class BoundedDownloadTarget(Protocol):
    path: Path
    name: str
    max_bytes: int

    def write(self, data: bytes) -> int: ...
    def seek(self, offset: int, whence: int = 0) -> int: ...
    def tell(self) -> int: ...
    def truncate(self, size: int | None = None) -> int: ...
    def flush(self) -> None: ...


class ResolvedPost(Protocol):
    text: str
    has_media: bool
    items: tuple[MediaItem, ...]

    async def download(self, item: MediaItem, destination: Path | BoundedDownloadTarget,
                       progress: Progress,
                       trace: JobTrace | None = None) -> Path | None: ...


class MediaSource(Protocol):
    async def resolve(self, link: ParsedLink, trace: JobTrace | None = None) -> ResolvedPost | None: ...


class Delivery(Protocol):
    async def send_text(self, chat: int, text: str,
                        trace: JobTrace | None = None) -> None: ...
    async def send_media(self, chat: int, files: list[DownloadedMedia], progress: Progress,
                         trace: JobTrace | None = None) -> DeliveryResult: ...
    async def send_media_stream(self, chat: int, files: AsyncIterable[DownloadedMedia],
                                 expected_total_bytes: int, progress: Progress,
                                 trace: JobTrace | None = None) -> DeliveryResult: ...


class Workspace(Protocol):
    def reserve(self, size: int, *, on_wait: Callable[[], Awaitable[None]] | None = None
                ) -> AbstractAsyncContextManager[object]: ...
    def create(self, message_id: int, *, reservation: object | None = None
               ) -> AbstractContextManager[Path]: ...
    def bounded_writer(self, path: Path, max_bytes: int
                       ) -> AbstractContextManager[BoundedDownloadTarget]: ...


class CopyObserver(Protocol):
    async def notice(self, code: str, **data) -> None: ...
    def download_progress(self, index: int, done: int, total: int) -> None: ...
    def upload_progress(self, done: int, total: int) -> None: ...
    def resume_progress(self) -> None: ...
    async def close(self) -> None: ...


class AccessStore(Protocol):
    def is_allowed(self, uid: int) -> bool: ...
    def is_admin(self, uid: int) -> bool: ...
    def grant(self, uid: int) -> bool: ...
    def revoke(self, uid: int) -> bool: ...
    def ids(self) -> list[int]: ...
    def admins(self) -> list[int]: ...


class Preferences(Protocol):
    def get(self, uid: int) -> MediaKind | None: ...
    def set(self, uid: int, kind: MediaKind | None) -> None: ...


class Membership(Protocol):
    async def join(self, kind: str, value: str) -> str: ...


class OwnerSessionAuthentication(Protocol):
    async def connect(self) -> None: ...
    async def is_authorized(self) -> bool: ...
    async def request_code(self, phone: str) -> OwnerAuthResult: ...
    async def sign_in_code(self, challenge_id: str, code: str) -> OwnerAuthResult: ...
    async def sign_in_password(self, password: str) -> OwnerAuthResult: ...


class JobStore(Protocol):
    async def accept(self, job: CopyJobInput, *, max_pending: int,
                     max_pending_per_user: int) -> JobAdmission: ...
    async def get_job(self, job_id: str) -> CopyJobSnapshot | None: ...
    async def request_cancel(self, job_id: str) -> JobCancellationDecision: ...
    async def claim_next(self) -> CopyJobInput | None: ...
    async def heartbeat(self, job_id: str, lease_generation: int) -> bool: ...
    async def set_stage(self, job_id: str, stage: str,
                        lease_generation: int) -> None: ...
    async def mark_send_intent(self, job_id: str,
                               lease_generation: int,
                               intent: DeliveryIntent | None = None) -> str | None: ...
    async def record_delivery_outcomes(self, job_id: str, attempt_id: str,
                                       outcomes: tuple[DeliveryOutcome, ...],
                                       lease_generation: int) -> None: ...
    async def delivery_summary(self, job_id: str) -> dict: ...
    async def cancellation_requested(self, job_id: str) -> bool: ...
    async def mark_waiting(self, job_id: str, wait_seconds: float,
                           wait_kind: str, wait_account: str,
                           lease_generation: int) -> bool: ...
    async def resume_waiting(self, job_id: str, lease_generation: int) -> bool: ...
    async def finish(self, job_id: str, state: str, result: dict,
                     lease_generation: int) -> None: ...
    async def expire_deadline(self, job_id: str, result: dict,
                              lease_generation: int) -> JobState | None: ...
    async def recover_interrupted(self) -> None: ...
    async def release_interrupted(self, job_id: str,
                                  lease_generation: int) -> None: ...


class PerformanceSink(Protocol):
    def write(self, event: dict) -> None: ...


class JobRunner(Protocol):
    async def cancel(self, job_id: str) -> None: ...
